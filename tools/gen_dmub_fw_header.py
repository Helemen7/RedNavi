"""Turn the DMCUB firmware into a C header for local builds (git-ignored, firmware is not redistributed).

    python3 tools/gen_dmub_fw_header.py dcn_3_2_0_dmcub.bin 57856 RedNavi/dmub_fw.h

The second argument is the VBIOS size in bytes; the probe refuses to run if the card reports another size.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dmub_layout import layout  # noqa: E402


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    fw = open(sys.argv[1], "rb").read()
    vbios = int(sys.argv[2])
    meta, inst, windows, total = layout(fw, vbios)
    with open(sys.argv[3], "w") as f:
        f.write(f"// Generated by tools/gen_dmub_fw_header.py from {sys.argv[1]}. Do not commit.\n")
        f.write(f"#define kRNDmubVbiosSize {vbios}u\n#define kRNDmubInstSize {len(inst)}u\n#define kRNDmubBlockSize {total}u\n")
        f.write(f"#define kRNDmubFwVersion 0x{meta['fw_version']:x}u\n")
        for name, base, size in windows:
            f.write(f"#define kRNDmubWin_{name}_Off 0x{base:x}u\n#define kRNDmubWin_{name}_Size {size}u\n")
        uoff = int.from_bytes(fw[24:28], "little")
        full = fw[uoff:uoff + int.from_bytes(fw[32:36], "little")]   # PSP header, code, PSP footer: what LOAD_IP_FW takes
        f.write(f"#define kRNDmubSignedSize {len(full)}u\n")
        f.write("static const unsigned char kRNDmubSigned[] = {\n")
        for j in range(0, len(full), 16):
            f.write("    " + ", ".join(f"0x{x:02x}" for x in full[j:j + 16]) + ",\n")
        f.write("};\n")
        f.write("static const unsigned char kRNDmubInst[] = {\n")
        for j in range(0, len(inst), 16):
            f.write("    " + ", ".join(f"0x{x:02x}" for x in inst[j:j + 16]) + ",\n")
        f.write("};\n")
    print(f"{len(inst)} bytes of code, block {total} bytes, firmware 0x{meta['fw_version']:x}")


if __name__ == "__main__":
    main()

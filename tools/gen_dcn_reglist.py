"""Build the list of DCN 3.2 registers (base index 2 of the DMU block) used to compare display states.

Reads dcn_3_2_0_offset.h (Linux, MIT) and writes
  tools/dcn32_reglist.txt   one "NAME dword_offset" per line, for tools/linux_dcn_dump.py
  RedNavi/dcn_reglist.h     the offsets as a C array, for the probe's rednavi_dcn_dump=1

    python3 tools/gen_dcn_reglist.py dcn_3_2_0_offset.h
"""
import re
import sys

SKIP = ("DMCUB", "AZ", "AZF0", "AZALIA")   # the DMCUB is ours to drive; audio blocks are not needed


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    regs, base = {}, {}
    for line in open(sys.argv[1]):
        m = re.match(r"#define reg(\w+)_BASE_IDX\s+(\d+)", line)
        if m:
            base[m.group(1)] = int(m.group(2))
            continue
        m = re.match(r"#define reg(\w+)\s+(0x[0-9a-fA-F]+)", line)
        if m:
            regs[m.group(1)] = int(m.group(2), 16)
    out = sorted(((o, n) for n, o in regs.items()
                  if base.get(n) == 2 and not n.startswith(SKIP) and not re.match(r"[A-Z]+\d*_", n.split("_")[0] + "_") is None
                  and not any(n.startswith(p + "_") or re.match(p + r"\d+_", n) for p in SKIP)),
                 key=lambda x: x[0])
    with open("tools/dcn32_reglist.txt", "w") as f:
        for o, n in out:
            f.write(f"{n} 0x{o:x}\n")
    with open("RedNavi/dcn_reglist.h", "w") as f:
        f.write("// Generated by tools/gen_dcn_reglist.py from dcn_3_2_0_offset.h (register names/offsets, MIT).\n")
        f.write("// Dword offsets from the DMU block base index 2; kRNDcnRegs[i] pairs with line i of tools/dcn32_reglist.txt.\n")
        f.write(f"#define kRNDcnRegCount {len(out)}u\nstatic const unsigned short kRNDcnRegs[] = {{\n")
        for j in range(0, len(out), 12):
            f.write("    " + ", ".join(f"0x{o:x}" for o, _ in out[j:j + 12]) + ",\n")
        f.write("};\n")
    print(len(out), "registers, max offset", hex(out[-1][0]))


if __name__ == "__main__":
    main()

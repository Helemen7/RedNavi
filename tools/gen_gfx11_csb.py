"""Generate RedNavi/gfx11_csb.h, the default context register values (the "clear state") that the command processor of GC 11 needs before the first draw, from Linux's
drivers/gpu/drm/amd/amdgpu/clearstate_gfx11.h (MIT licence, Copyright 2021 Advanced Micro Devices, Inc.; see NOTICE).

    tools/gen_gfx11_csb.py path/to/clearstate_gfx11.h RedNavi/gfx11_csb.h

The output is plain data: for each extent (a run of consecutive context registers) its first register number and its values, holes included (a hole is a register that the
list skips over and the driver writes as 0)."""
import re
import sys

src = open(sys.argv[1]).read()
arrays = {}
for m in re.finditer(r'static const unsigned int (gfx11_SECT_CONTEXT_def_\d+)\[\]\s*=\s*\{(.*?)\n\};', src, re.S):
    vals = []
    for line in m.group(2).split('\n'):
        line = line.strip()
        if not line:
            continue
        v = re.match(r'(0x[0-9a-fA-F]+|0),', line)
        if not v:
            raise SystemExit('cannot parse: ' + line)
        vals.append(int(v.group(1), 16))
    arrays[m.group(1)] = vals
extents = re.findall(r'\{(gfx11_SECT_CONTEXT_def_\d+),\s*(0x[0-9a-fA-F]+),\s*(\d+)\s*\}', src)
out = ['// Generated by tools/gen_gfx11_csb.py from Linux\'s clearstate_gfx11.h (MIT licence, Copyright 2021 Advanced Micro Devices, Inc., see NOTICE). Do not edit.',
       '// The default context registers of GC 11 (the clear state): extents of consecutive registers, their numbers in the 0xA000 context register space.',
       '#ifndef REDNAVI_GFX11_CSB_H', '#define REDNAVI_GFX11_CSB_H', '']
for name, first, count in extents:
    vals = arrays[name]
    assert len(vals) == int(count), (name, len(vals), count)
    out.append('static const unsigned int k%s[] = {' % name.replace('gfx11_SECT_CONTEXT_', 'Csb_'))
    for i in range(0, len(vals), 8):
        out.append('    ' + ', '.join('0x%08x' % v for v in vals[i:i + 8]) + ',')
    out.append('};')
out.append('')
out.append('struct rn_csb_extent { const unsigned int *values; unsigned int first_reg, count; };')
out.append('static const struct rn_csb_extent kGfx11CsbExtents[] = {')
for name, first, count in extents:
    out.append('    {k%s, %s, %s},' % (name.replace('gfx11_SECT_CONTEXT_', 'Csb_'), first, count))
out.append('};')
out.append('')
out.append('#endif')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('%d extents, %d registers' % (len(extents), sum(int(c) for _, _, c in extents)))

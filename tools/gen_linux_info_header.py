"""Turn the raw DRM_AMDGPU_INFO answers of a Linux run (tools/linux_amdgpu_info_raw.py) into RedNavi/linux_info_<name>.h.

    python3 tools/gen_linux_info_header.py docs/logs/linux-reference/amdgpu_info_raw_navi32.txt RedNavi/linux_info_navi32.h navi32
    python3 tools/gen_linux_info_header.py docs/logs/navi33/rx7600-frame121/amdgpu_info_raw.txt docs/logs/navi33/linux_info_navi33.h navi33

The third argument names the ASIC: every symbol of the header ends with it, so the headers of several ASICs can be built into
one kext. The row of the ASIC in RedNavi/asic.cpp points at kRNLinuxInfo_<name>.

The header holds what the Linux kernel told RADV on this card: the exact DEV_INFO byte length returned by the capture kernel, the HW_IP_INFO and HW_IP_COUNT answers, the firmware versions and the
MAX_IBS array. DEV_INFO size can vary with the kernel UAPI version; rn_drm_info carries that size and infoQuery copies the smaller of the caller buffer and captured payload. They are numbers and flags, no firmware. The kext's infoQuery answers with them (and overrides what macOS does differently).
"""
import os
import re
import sys


def main():
    if len(sys.argv) != 4 or not re.fullmatch(r"[a-z0-9]+", sys.argv[3]):
        sys.exit(__doc__)
    raw = open(sys.argv[1]).read()
    name = sys.argv[3]

    def bytes_of(label):
        m = re.search(r"^%s\s+(\d+) bytes: ([0-9a-f]+)$" % re.escape(label), raw, re.M)
        if not m:
            sys.exit("no answer for " + label)
        return bytes.fromhex(m.group(2))

    out = ["// Generated by tools/gen_linux_info_header.py from %s. Do not edit." % os.path.relpath(sys.argv[1], os.getcwd()),
           "// What the Linux kernel (amdgpu) answered to DRM_AMDGPU_INFO on this ASIC: numbers and flags, no firmware.",
           "#ifndef REDNAVI_LINUX_INFO_%s_H" % name.upper(), "#define REDNAVI_LINUX_INFO_%s_H" % name.upper(), "", "#include <stdint.h>", '#include "asic.h"', ""]

    def array(name, data, per_line=16, ctype="uint8_t"):
        out.append("static const %s %s[%d] = {" % (ctype, name, len(data)))
        for i in range(0, len(data), per_line):
            out.append("    " + ", ".join("0x%02x" % b for b in data[i:i + per_line]) + ",")
        out.append("};")

    dev = bytes_of("DEV_INFO")
    array("kRNLinuxDevInfo_" + name, dev)
    out.append("")
    # HW_IP_INFO per type (instance 0) and HW_IP_COUNT
    counts = []
    for t in range(10):
        m = re.search(r"^HW_IP_COUNT %d\s+4 bytes: ([0-9a-f]{8})$" % t, raw, re.M)
        counts.append(int.from_bytes(bytes.fromhex(m.group(1)), "little") if m else 0)
    out.append("static const uint32_t kRNLinuxHwIpCount_%s[10] = {%s};" % (name, ", ".join(str(c) for c in counts)))
    out.append("static const uint8_t kRNLinuxHwIpInfo_%s[10][40] = {" % name)
    for t in range(10):
        d = bytes_of("HW_IP_INFO %d.0" % t)
        assert len(d) == 40
        out.append("    {" + ", ".join("0x%02x" % b for b in d) + "},")
    out.append("};")
    out.append("")
    # firmware versions: (type, version, feature) from the answers with index 0
    fw = {}
    for m in re.finditer(r"^FW_VERSION type 0x([0-9a-f]{2}) instance 0 index 0: ([0-9a-f]{16})$", raw, re.M):
        t = int(m.group(1), 16)
        d = bytes.fromhex(m.group(2))
        fw[t] = (int.from_bytes(d[:4], "little"), int.from_bytes(d[4:], "little"))
    out.append("static const struct rn_drm_fw kRNLinuxFw_%s[] = {" % name)
    for t in sorted(fw):
        out.append("    {0x%02x, 0x%08x, 0x%08x}," % (t, fw[t][0], fw[t][1]))
    out.append("};")
    out.append("")
    ibs = bytes_of("MAX_IBS")
    out.append("static const uint32_t kRNLinuxMaxIbs_%s[%d] = {%s};" % (name, len(ibs) // 4, ", ".join(str(int.from_bytes(ibs[i:i + 4], "little")) for i in range(0, len(ibs), 4))))
    out.append("")
    out.append("static const struct rn_drm_info kRNLinuxInfo_%s = {" % name)
    out.append("    kRNLinuxDevInfo_%s, %d, kRNLinuxHwIpCount_%s, kRNLinuxHwIpInfo_%s, kRNLinuxFw_%s, %d, kRNLinuxMaxIbs_%s, %d," % (name, len(dev), name, name, name, len(fw), name, len(ibs) // 4))
    out.append("};")
    out += ["", "#endif", ""]
    open(sys.argv[2], "w").write("\n".join(out))
    print("DEV_INFO %d bytes, %d firmware versions" % (len(dev), len(fw)))


main()

"""Turn the SMU firmware into a C header for local builds (git-ignored, firmware is not redistributed).

    python3 tools/gen_smu_fw_header.py smu_13_0_10.bin RedNavi/smu_fw.h

What Linux hands to the PSP for AMDGPU_UCODE_ID_SMC (GFX_FW_TYPE_SMU, amdgpu_ucode_init_single_fw): the ucode array of the
common firmware header, i.e. ucode_size_bytes bytes starting at ucode_array_offset_bytes.
"""
import struct
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    fw = open(sys.argv[1], "rb").read()
    size_bytes, hdr_size, vmaj, vmin, imaj, imin, ucode_version, ucode_size, array_off, crc = struct.unpack_from("<IIHHHHIIII", fw, 0)
    if size_bytes != len(fw) or array_off + ucode_size > len(fw):
        sys.exit("not a valid amdgpu firmware file (size %d, header says %d)" % (len(fw), size_bytes))
    payload = fw[array_off:array_off + ucode_size]
    with open(sys.argv[2], "w") as f:
        f.write(f"// Generated by tools/gen_smu_fw_header.py from {sys.argv[1]}. Do not commit.\n")
        f.write(f"#define kRNSmuFwVersion 0x{ucode_version:x}u\n#define kRNSmuFwSize {len(payload)}u\n")
        f.write("static const unsigned char kRNSmuFw[] = {\n")
        for j in range(0, len(payload), 16):
            f.write("    " + ", ".join(f"0x{x:02x}" for x in payload[j:j + 16]) + ",\n")
        f.write("};\n")
    print(f"header v{vmaj}.{vmin}, ip {imaj}.{imin}, ucode version 0x{ucode_version:x}, {len(payload)} bytes")


if __name__ == "__main__":
    main()

"""Generate RedNavi/gc_regs.h from the AMD gc_11_0_3 register headers (MIT licence, see NOTICE).

    python3 tools/gen_gc_regs.py gc_11_0_3_offset.h gc_11_0_3_sh_mask.h tools/gc_regs_spec.txt gc_11_0_0_default.h > RedNavi/gc_regs.h

The offsets and fields are those of GC 11.0.3 (Navi 32): its memory hub registers sit elsewhere than in gc_11_0_0. Linux has
no gc_11_0_3_default.h, so the reset values come from gc_11_0_0_default.h.

Only the registers and fields listed in tools/gc_regs_spec.txt are emitted, with their base index.
"""
import re
import sys


def main():
    # Optional trailing "--guard NAME --from TEXT" for the other IP blocks (OSSSYS, NBIO): the same generator, another header set.
    args, guard, src = sys.argv[1:], "REDNAVI_GC_REGS_H", "the AMD gc_11_0_3 headers, reset values from gc_11_0_0_default.h"
    while "--guard" in args:
        i = args.index("--guard"); guard = args[i + 1]; del args[i:i + 2]
    while "--from" in args:
        i = args.index("--from"); src = args[i + 1]; del args[i:i + 2]
    if len(args) not in (3, 4):
        sys.exit(__doc__)
    off = open(args[0]).read()
    mask = open(args[1]).read()
    dflt = open(args[3]).read() if len(args) == 4 else ""
    print("// Generated by tools/gen_gc_regs.py from %s (MIT, see NOTICE). Do not edit." % src)
    print("#ifndef %s\n#define %s\n" % (guard, guard))
    for line in open(args[2]):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, _, fields = line.partition(":")
        m = re.search(r"#define reg%s\s+(0x[0-9a-fA-F]+)" % re.escape(name), off)
        b = re.search(r"#define reg%s_BASE_IDX\s+(\d+)" % re.escape(name), off)
        if not m or not b:
            sys.exit("register %s not found" % name)
        print(f"#define reg{name} {m.group(1)}\n#define reg{name}_BASE_IDX {b.group(1)}")
        d = re.search(r"#define reg%s_DEFAULT\s+(0x[0-9a-fA-F]+)" % re.escape(name), dflt)
        if d:
            print(f"#define reg{name}_DEFAULT {d.group(1)}")
        for fld in [f for f in fields.split(",") if f]:
            s = re.search(r"#define %s__%s__SHIFT\s+(0x[0-9a-fA-F]+)" % (re.escape(name), re.escape(fld)), mask)
            k = re.search(r"#define %s__%s_MASK\s+(0x[0-9a-fA-F]+)L?" % (re.escape(name), re.escape(fld)), mask)
            if not s or not k:
                sys.exit("field %s.%s not found" % (name, fld))
            print(f"#define {name}__{fld}__SHIFT {s.group(1)}\n#define {name}__{fld}_MASK {k.group(1)}u")
        print()
    print("#endif")


if __name__ == "__main__":
    main()

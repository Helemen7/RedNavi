"""Extract the bootloader-loadable components of an AMD PSP firmware file into a C header.

The header is git-ignored: firmware is not redistributed from this repository.

    python3 tools/gen_psp_fw_header.py psp_13_0_10_sos.bin RedNavi/psp_fw.h

Components are emitted in the order amdgpu loads them (psp_hw_start): KDB, SYS_DRV, SOC_DRV,
INTF_DRV, DBG_DRV, RAS_DRV, SOS. Command values are PSP_BL__* from amdgpu_psp.h.
"""
import struct
import sys

NAMES = ["UNKNOWN", "SOS", "SYS_DRV", "KDB", "TOC", "SPL", "RL", "SOC_DRV", "INTF_DRV",
         "DBG_DRV", "RAS_DRV", "IPKEYMGR_DRV", "SPDM_DRV"]
ORDER = [("KDB", 0x80000), ("SYS_DRV", 0x10000), ("SOC_DRV", 0xB0000), ("INTF_DRV", 0xD0000),
         ("DBG_DRV", 0xC0000), ("RAS_DRV", 0xE0000), ("SOS", 0x20000)]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    path, out = sys.argv[1:]
    b = open(path, "rb").read()
    uoff, = struct.unpack_from("<I", b, 24)
    count, = struct.unpack_from("<I", b, 32)
    found = {}
    for i in range(count):
        t, ver, off, size = struct.unpack_from("<IIII", b, 36 + 16 * i)
        found[NAMES[t]] = (ver, b[uoff + off:uoff + off + size])
    with open(out, "w") as f:
        f.write(f"// Generated by tools/gen_psp_fw_header.py from {path}. Do not commit.\n")
        entries = []
        for name, cmd in ORDER:
            if name not in found:
                continue
            ver, data = found[name]
            f.write(f"static const unsigned char kRnFw_{name}[] = {{\n")
            for j in range(0, len(data), 16):
                f.write("    " + ", ".join(f"0x{x:02x}" for x in data[j:j + 16]) + ",\n")
            f.write("};\n")
            entries.append((name, cmd, ver, len(data)))
            print(f"{name}: {len(data)} bytes, version 0x{ver:x}, command 0x{cmd:x}")
        f.write("static const struct { const char *name; unsigned int cmd; unsigned int version; const unsigned char *data; unsigned int size; } kRNPspChain[] = {\n")
        for name, cmd, ver, n in entries:
            f.write(f'    {{"{name}", 0x{cmd:x}, 0x{ver:x}, kRnFw_{name}, {n}}},\n')
        f.write("};\n")
        if "TOC" in found:
            ver, data = found["TOC"]
            f.write("static const unsigned char kRNPspToc[] = {\n")
            for j in range(0, len(data), 16):
                f.write("    " + ", ".join(f"0x{x:02x}" for x in data[j:j + 16]) + ",\n")
            f.write("};\n")
            print(f"TOC: {len(data)} bytes, version 0x{ver:x} (LOAD_TOC)")


if __name__ == "__main__":
    main()

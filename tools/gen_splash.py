"""Turn a splash PNG into RedNavi/splash_<W>x<H>.h: the pixels as XRGB8888 in run-length form.

    python3 tools/gen_splash.py assets/splash_1920x1080.png RedNavi/splash_1920x1080.h

The header holds two arrays, the colour of each run and its length in pixels, in scan order, and the size. fillScanout
writes the runs into the scanout buffer instead of the colour test pattern. Pixels with an alpha below 255 are blended
over black.
"""
import sys
from PIL import Image


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    im = Image.open(sys.argv[1]).convert("RGBA")
    w, h = im.size
    bg = Image.new("RGBA", im.size, (0, 0, 0, 255))
    im = Image.alpha_composite(bg, im).convert("RGB")
    px = im.load()
    colours, lengths = [], []
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            v = (r << 16) | (g << 8) | b
            if colours and colours[-1] == v and lengths[-1] < 0xFFFFFFFF:
                lengths[-1] += 1
            else:
                colours.append(v)
                lengths.append(1)
    name = "kSplash%dx%d" % (w, h)
    out = ["// Generated by tools/gen_splash.py from %s. Do not edit." % sys.argv[1].split("/")[-1],
           "// The RedNavi splash screen by Helemen7, under the licence of the project (BSD-3-Clause).",
           "#ifndef REDNAVI_SPLASH_%dX%d_H" % (w, h), "#define REDNAVI_SPLASH_%dX%d_H" % (w, h), "",
           "#include <stdint.h>", "",
           "static const uint32_t %sWidth = %d, %sHeight = %d, %sRuns = %d;" % (name, w, name, h, name, len(colours)),
           "static const uint32_t %sColour[] = {" % name]
    for i in range(0, len(colours), 12):
        out.append("    " + ", ".join("0x%06x" % c for c in colours[i:i + 12]) + ",")
    out.append("};")
    out.append("static const uint32_t %sLength[] = {" % name)
    for i in range(0, len(lengths), 12):
        out.append("    " + ", ".join(str(n) for n in lengths[i:i + 12]) + ",")
    out.append("};")
    out += ["", "#endif", ""]
    open(sys.argv[2], "w").write("\n".join(out))
    print("%dx%d: %d runs" % (w, h, len(colours)))


main()
